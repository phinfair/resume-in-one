/**
 * 检查院校标签
 * @param {string} schoolName
 * @returns {{ is985: boolean, is211: boolean, isDoubleTop: boolean }}
 */
function checkSchoolTags(schoolName) {
  if (!schoolName) return { is985: false, is211: false, isDoubleTop: false };

  // 去除后缀变体（如 "清华大学（深圳）"）
  const normalized = schoolName.trim().replace(/[（(].*/g, '').trim();

  // 模糊匹配：只要名字包含关键词或关键词包含名字
  const match = (set) => {
    for (const s of set) {
      if (s.includes(normalized) || normalized.includes(s)) return true;
    }
    return false;
  };

  return {
    is985: match(SCHOOLS_985),
    is211: match(SCHOOLS_211),
    isDoubleTop: match(SCHOOLS_DOUBLE_TOP),
  };
}

